import { describe, expect, test } from "vitest";
import { looksAutoGenerated } from "./autoCaptions";
import type { Cue } from "./types";

const cues = (texts: string[]): Cue[] =>
  texts.map((text, i) => ({ text, start: i * 2, duration: 2 }));

const repeat = (line: string, n: number) => Array.from({ length: n }, () => line);

describe("looksAutoGenerated", () => {
  test("flags long tracks with no sentence punctuation", () => {
    expect(looksAutoGenerated(cues(repeat("so today we are going to talk about", 20)))).toBe(true);
  });

  test("does not flag punctuated captions", () => {
    expect(
      looksAutoGenerated(cues(repeat("Today we talk about habits. Why do they matter?", 20))),
    ).toBe(false);
  });

  test("ignores decimal points and very short tracks", () => {
    expect(looksAutoGenerated(cues(repeat("prices rose 2.5 percent this year and more", 20)))).toBe(
      true,
    );
    expect(looksAutoGenerated(cues(["hello there", "how are you"]))).toBe(false);
  });
});
