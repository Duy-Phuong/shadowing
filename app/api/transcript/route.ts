import { NextResponse } from "next/server";
import { extractVideoId } from "@/lib/youtube";
import { segmentSentences } from "@/lib/segmentSentences";
import { findTimingProblems } from "@/lib/sentenceTiming";
import { looksAutoGenerated } from "@/lib/autoCaptions";
import { loadTranscript } from "@/lib/transcriptStore";
import { describeCaptionError } from "@/lib/captionErrors";
import { readBookmarks } from "@/lib/bookmarksFile";
import type { Transcript } from "@/lib/types";

interface ErrorBody {
  error: string;
  message: string;
}

const fail = (status: number, error: string, message: string) =>
  NextResponse.json<ErrorBody>({ error, message }, { status });

export async function POST(request: Request) {
  let body: { url?: string };
  try {
    body = (await request.json()) as { url?: string };
  } catch {
    return fail(400, "invalid_request", "Request body must be JSON.");
  }

  const url = body.url;
  if (typeof url !== "string" || url.trim() === "") {
    return fail(400, "invalid_request", "A YouTube URL is required.");
  }

  const videoId = extractVideoId(url);
  if (!videoId) {
    return fail(400, "invalid_url", "That doesn't look like a YouTube link.");
  }

  let stored;
  try {
    const starred = (await readBookmarks()).some((b) => b.videoId === videoId);
    stored = await loadTranscript(videoId, starred);
  } catch (err) {
    console.warn(`[transcript] ${videoId}:`, err);
    const { status, error, message } = describeCaptionError(err);
    return fail(status, error, message);
  }

  const sentences = segmentSentences(stored.cues);
  if (sentences.length === 0) {
    return fail(422, "no_transcript", "This video's captions are empty. Try another video.");
  }

  // Timing the player can't loop through is a segmentation bug, not a bad video.
  // Serve the transcript anyway — reading along still works — but say so here
  // rather than let it surface as sentences that won't stop playing.
  const problems = findTimingProblems(sentences);
  if (problems.length > 0) {
    console.warn(
      `[transcript] ${videoId}: ${problems.length} timing problem(s) in ` +
        `${sentences.length} sentences\n  ${problems.slice(0, 5).join("\n  ")}`,
    );
  }

  return NextResponse.json<Transcript>({
    videoId,
    title: stored.title,
    sentences,
    autoCaptions: looksAutoGenerated(stored.cues),
  });
}
